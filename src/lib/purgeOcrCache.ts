// Разовая уборка старых словарей распознавания.
//
// Движок распознавания раньше складывал словари в память браузера, и они
// переживали обновление программы. После обновления там оставались словари
// от прошлой сборки — движок молча брал их вместо новых, спотыкался и
// распознавание срывалось. Теперь словари читаются только из файлов
// программы, а этот остаток нужно убрать один раз.

const DONE = 'pv_ocr_cache_cleared';
const DB = 'keyval-store';

export const purgeOcrCache = () => {
  if (localStorage.getItem(DONE)) return;

  // Помечаем сразу: даже если уборка не удалась, второй раз лезть незачем
  localStorage.setItem(DONE, '1');

  try {
    indexedDB.deleteDatabase(DB);
  } catch {
    // Память браузера недоступна — не беда, словари и так берутся из файлов
  }
};
