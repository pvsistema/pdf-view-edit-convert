export const readTerms = (): string[] => {
  try {
    const raw = localStorage.getItem(TERMS_KEY);
    return raw ? (JSON.parse(raw) as string[]) : [];
  } catch {
    return [];
  }
};

export const saveTerms = (list: string[]) => {
  const clean = [...new Set(list.map((t) => t.trim()).filter(Boolean))];
  try {
    localStorage.setItem(TERMS_KEY, JSON.stringify(clean));
  } catch {
    /* хранилище недоступно — список останется до закрытия окна */
  }
  return clean;
};

// Разбор текста, вставленного человеком: по слову в строке, через
// запятую или точку с запятой
export const parseTerms = (text: string) =>
  text
    .split(/[\n,;]+/)
    .flatMap((line) => line.trim().split(/\s+/))
    .map((t) => t.replace(/^[«"(]+|[»").,:!?]+$/g, ''))
    .filter((t) => t.length >= 2);
